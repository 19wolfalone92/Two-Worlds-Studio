"""Reproducible private Work-art cinematic benchmark inside TWO WORLDS Studio.

Run only with the unshared original Work v1.1 handoff. This creates a
10-second review-only cinematic acting test: no scripts changed, no TikTok
publication, and private art is never written into the GitHub repository.

Requires optional: pip install opencv-python-headless. FFmpeg is required.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import multiprocessing as mp
import subprocess
import tempfile
import time
from pathlib import Path
from PIL import Image

try:
    from studio import private_mirror_benchmark as benchmark
except ImportError:
    import private_mirror_benchmark as benchmark

SCENE=None
FRAME_ROOT=None
FPS=24

def render_one(i):
    frame=SCENE.frame_at(i/FPS)
    Image.fromarray(frame,'RGB').save(FRAME_ROOT/f'{i:05}.jpg',format='JPEG',quality=96,subsampling=0)
    return i

def run(handoff:Path, output:Path, *,fps:int=24,seconds:int=10,
        workers:int=3,scale:float=1.0)->dict:
    global SCENE, FRAME_ROOT, FPS
    if not (.4<=scale<=1 and fps in (12,24) and seconds==10 and 1<=workers<=6):
        raise ValueError('Benchmark requires 10 seconds, 12/24 FPS, 40–100% native pixels')
    if not handoff.is_file():
        raise FileNotFoundError('Private Work v1.1 Studio handoff ZIP must be provided')
    if output.exists():
        raise FileExistsError('Do not overwrite existing owner-review video')
    images,original_voice=benchmark.art(handoff,scale)
    SCENE=benchmark.Scene(images)
    FPS=fps
    output.parent.mkdir(parents=True,exist_ok=True)
    started=time.monotonic()
    with tempfile.TemporaryDirectory(prefix='two-worlds-actor-demo-') as temp:
        FRAME_ROOT=Path(temp)
        # Linux fork preserves shared image arrays without pickling each frame.
        with mp.get_context('fork').Pool(workers) as pool:
            done=list(pool.imap_unordered(render_one,range(fps*seconds),chunksize=2))
        if len(done)!=fps*seconds or sorted(done)!=list(range(fps*seconds)):
            raise RuntimeError('Missing frame(s) in character benchmark')
        wav=FRAME_ROOT/'mira_original_voice.wav'
        wav.write_bytes(original_voice)
        cmd=['ffmpeg','-nostdin','-hide_banner','-loglevel','error','-y',
            '-framerate',str(fps),'-i',str(FRAME_ROOT/'%05d.jpg'),
            '-itsoffset','2.15','-i',str(wav),
            '-filter_complex',f'anoisesrc=color=brown:amplitude=0.008:sample_rate=48000:d={seconds}[noise];'
            '[noise]lowpass=f=130,volume=0.28[amb];'
            '[1:a]aresample=48000,volume=1.45[voc];'
            '[amb][voc]amix=inputs=2:duration=longest:dropout_transition=0[a]',
            '-map','0:v:0','-map','[a]','-vf','scale=1080:1920:flags=lanczos',
            '-t',str(seconds),'-c:v','libx264','-preset','veryfast','-crf','19',
            '-pix_fmt','yuv420p','-c:a','aac','-b:a','160k','-movflags','+faststart',str(output)]
        result=subprocess.run(cmd,capture_output=True,text=True,timeout=150)
        if result.returncode:
            output.unlink(missing_ok=True)
            raise RuntimeError('FFmpeg failed: '+result.stderr[-1500:])
    decoder=subprocess.run(['ffmpeg','-v','error','-i',str(output),'-f','null','-'],
                           capture_output=True,text=True,timeout=100)
    if decoder.returncode:
        output.unlink(missing_ok=True)
        raise RuntimeError('Final MP4 failed full decode: '+decoder.stderr[-1500:])
    manifest={
      'status':'TECHNICAL_BENCHMARK_OWNER_REVIEW_ONLY',
      'duration_seconds':seconds,'fps':fps,'output_resolution':'1080x1920',
      'working_resolution':f'{SCENE.w}x{SCENE.h}',
      'frames':fps*seconds,'all_frames_written':True,'full_decode':True,
      'actual_work_art':'Mira and Lyra Work pilot v1.1; no autogenerated substitute faces',
      'animation':'Two real arm joints with prepainted Work assets; root staging; glass interaction',
      'limitations':'No motion-capture, IK walking, lip phonemes or AI motion generation. Hand-masked shoulders remain subject to visual review.',
      'voice':'Original Work S03 Mira voice, not redubbed',
      'owner_approved':False,'publish_allowed':False,
      'public_repo_artwork_upload':False,
      'source_handoff_sha256':hashlib.sha256(handoff.read_bytes()).hexdigest(),
      'final_video_sha256':hashlib.sha256(output.read_bytes()).hexdigest(),
      'render_elapsed_seconds':round(time.monotonic()-started,2),
    }
    output.with_suffix('.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    return manifest

def main():
    p=argparse.ArgumentParser(description='Real Work Mira mirror shot (PRIVATE inputs, review-only output)')
    p.add_argument('--handoff',required=True,type=Path)
    p.add_argument('--output',required=True,type=Path)
    p.add_argument('--fps',type=int,default=24)
    p.add_argument('--seconds',type=int,default=10)
    p.add_argument('--workers',type=int,default=3)
    p.add_argument('--scale',type=float,default=1.0)
    opts=p.parse_args()
    print(json.dumps(run(opts.handoff,opts.output,fps=opts.fps,
                         seconds=opts.seconds,workers=opts.workers,scale=opts.scale),indent=2))

if __name__=='__main__':
    main()
