"""Official Hunyuan3D-2mv T4 benchmark on OFFICIAL PUBLIC DEMO VIEWS only.
Privacy: no user game screenshots and no actual figure generated by this benchmark.
Writes real GLB in owner-private Kaggle notebook; reports safe technical numbers.
"""
from __future__ import annotations
import hashlib,json,os,subprocess,sys,time
from pathlib import Path

def run(*cmd,timeout=900):
    subprocess.run(list(cmd),check=True,timeout=timeout)

def main():
    import torch
    root=Path("/kaggle/working")
    result=root/"tflex_v94_public_sample_technical_pilot.json"
    status={"project":"T-Flex 200mm","data":"TENCENT_OFFICIAL_PUBLIC_DEMO_ONLY",
            "real_personal_figure_generated":False,"model_loaded":False,
            "inference_executed":False,"glb_generated":False,"gpu_count":torch.cuda.device_count(),
            "devices":[{"name":torch.cuda.get_device_name(i),
                        "vram_gib":round(torch.cuda.get_device_properties(i).total_memory/(1024**3),2)}
                       for i in range(torch.cuda.device_count())],
            "error_type":None}
    try:
        if not torch.cuda.is_available():raise RuntimeError("CUDA GPU unavailable")
        repo=root/"Hunyuan3D-2"
        if not repo.is_dir():
            run("git","clone","--quiet","--depth","1","https://github.com/Tencent-Hunyuan/Hunyuan3D-2",str(repo),timeout=360)
        sha="f8db63096c8282cb27354314d896feba5ba6ff8a"
        run("git","-C",str(repo),"fetch","--quiet","--depth","1","origin",sha,timeout=300)
        run("git","-C",str(repo),"checkout","--quiet","--detach",sha,timeout=120)
        run(sys.executable,"-m","pip","install","-q",
             "diffusers>=0.30,<0.36","transformers>=4.48,<4.56",
             "accelerate>=1.0","einops","omegaconf","trimesh>=4.5",
             "pymeshlab","pygltflib","xatlas","ninja","pybind11",
             "huggingface_hub","safetensors",timeout=900)
        sys.path.insert(0,str(repo))
        from PIL import Image
        from hy3dgen.shapegen import Hunyuan3DDiTFlowMatchingPipeline
        views={}
        for name in ("front","left","back"):
            p=repo/"assets"/"example_mv_images"/"1"/(name+".png")
            if not p.is_file():raise FileNotFoundError("Official public demo "+name)
            views[name]=Image.open(p).convert("RGBA")
        status["official_demo_sha256"]={n:hashlib.sha256(
           (repo/"assets"/"example_mv_images"/"1"/(n+".png")).read_bytes()
           ).hexdigest() for n in views}
        start=time.monotonic()
        pipe=Hunyuan3DDiTFlowMatchingPipeline.from_pretrained(
            "tencent/Hunyuan3D-2mv",subfolder="hunyuan3d-dit-v2-mv-turbo",variant="fp16")
        status["model_loaded"]=True
        pipe.enable_model_cpu_offload()
        pipe.enable_flashvdm()
        torch.cuda.reset_peak_memory_stats()
        output=pipe(image=views,num_inference_steps=5,octree_resolution=256,
            num_chunks=8000,generator=torch.manual_seed(20261120),output_type="trimesh")
        status["inference_executed"]=True
        mesh=output[0]
        if len(mesh.faces)<3000:raise RuntimeError("Real mesh below minimum face count")
        f=root/"TFLEX_PUBLIC_DEMO_MV_TURBO_GPU_PROOF_UNAPPROVED.glb"
        mesh.export(f)
        status["glb_generated"]=True
        status["faces"]=len(mesh.faces)
        status["glb_bytes"]=f.stat().st_size
        status["glb_sha256"]=hashlib.sha256(f.read_bytes()).hexdigest()
        status["gpu_peak_allocated_gib"]=round(torch.cuda.max_memory_allocated()/1024**3,2)
        status["seconds"]=round(time.monotonic()-start,2)
    except BaseException as exc:
        status["error_type"]=type(exc).__name__
        status["error_phase"]=("install_or_model" if not status["model_loaded"] else
                              "inference" if not status["inference_executed"] else "mesh")
    finally:
        result.write_text(json.dumps(status,indent=2))
        print("TFLEX_HUNYUAN_PUBLIC_SAMPLE_SAFE_RESULT",json.dumps({
            k:status.get(k) for k in ("gpu_count","model_loaded","inference_executed",
            "glb_generated","faces","glb_bytes","gpu_peak_allocated_gib","seconds","error_type","error_phase")}))
    if not status["glb_generated"]:sys.exit(2)

if __name__=="__main__":main()
